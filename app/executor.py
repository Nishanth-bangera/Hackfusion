"""
Executor — writes draft purchase orders and email files to outbox/.
No real email is sent. No real PO is issued. All files are labeled DRAFT.
"""
import json
from datetime import date, timedelta
from pathlib import Path

from app.db import get_connection

OUTBOX = Path(__file__).resolve().parent.parent / "outbox"


def _record_action(job_id: int, action_type: str, status: str, payload: dict) -> int:
    conn = get_connection()
    try:
        cur = conn.execute(
            "INSERT INTO actions (job_id, action_type, status, payload_json) VALUES (?,?,?,?)",
            (job_id, action_type, status, json.dumps(payload)),
        )
        conn.commit()
        return cur.lastrowid
    finally:
        conn.close()


def execute_actions(job_id: int, approved_actions: list[dict]) -> list[str]:
    """
    Write a draft PO file and a draft email file for each approved action.
    Returns a list of file paths written.
    """
    OUTBOX.mkdir(exist_ok=True)
    files: list[str] = []

    for n, action in enumerate(approved_actions, start=1):
        order_id = action.get("order_id", "?")
        supplier_name = action.get("supplier_name", "Unknown Supplier")
        sku = action.get("sku", "UNKNOWN-SKU")
        quantity = action.get("quantity", 0)
        unit_price = action.get("unit_price_inr", 0.0)
        lead_time = action.get("lead_time_days", 0)
        total_inr = quantity * unit_price
        expected_arrival = (date.today() + timedelta(days=lead_time)).isoformat()
        po_number = f"PO-{job_id}-{n}"

        # --- Draft Purchase Order ---
        po_text = (
            f"DRAFT PURCHASE ORDER — {po_number}\n"
            f"{'=' * 54}\n"
            f"[THIS IS A DRAFT — NOT A LEGALLY BINDING DOCUMENT]\n"
            f"[All company data is MOCK data for demonstration purposes]\n"
            f"\n"
            f"Order ID (internal ref) : {order_id}\n"
            f"PO Number               : {po_number}\n"
            f"Supplier                : {supplier_name}\n"
            f"SKU                     : {sku}\n"
            f"Quantity                : {quantity:,} units\n"
            f"Unit Price (INR)        : \u20b9{unit_price:,.2f}\n"
            f"Total Value (INR)       : \u20b9{total_inr:,.2f}\n"
            f"Expected Arrival        : {expected_arrival}\n"
            f"Lead Time               : {lead_time} days\n"
            f"\n"
            f"--- Auto-generated by SupplyShield Executor (MOCK) ---\n"
        )
        po_path = OUTBOX / f"{po_number}.txt"
        po_path.write_text(po_text, encoding="utf-8")
        files.append(str(po_path))

        po_payload = {
            "po_number": po_number,
            "order_id": order_id,
            "supplier": supplier_name,
            "sku": sku,
            "quantity": quantity,
            "unit_price_inr": unit_price,
            "total_inr": total_inr,
            "expected_arrival": expected_arrival,
        }
        _record_action(job_id, "draft_po", "executed", po_payload)

        # --- Draft Email ---
        email_text = (
            f"DRAFT EMAIL — {po_number}\n"
            f"{'=' * 54}\n"
            f"[DRAFT — NOT SENT — SupplyShield Executor]\n"
            f"[All company data is MOCK data for demonstration purposes]\n"
            f"\n"
            f"To      : procurement@mockcompany.example\n"
            f"Subject : [DRAFT] Alternative Supply Arranged \u2014 {sku} \u2014 {po_number}\n"
            f"\n"
            f"Dear Procurement Team,\n"
            f"\n"
            f"SupplyShield has identified an alternative supplier following a supply\n"
            f"chain disruption. A draft purchase order has been prepared for your review.\n"
            f"\n"
            f"  PO Number  : {po_number}\n"
            f"  Supplier   : {supplier_name}\n"
            f"  SKU        : {sku}\n"
            f"  Quantity   : {quantity:,} units\n"
            f"  Unit Price : \u20b9{unit_price:,.2f}\n"
            f"  Total      : \u20b9{total_inr:,.2f}\n"
            f"  Arrival    : {expected_arrival}\n"
            f"\n"
            f"Please review and approve before issuing to the supplier.\n"
            f"\n"
            f"This message was generated automatically by SupplyShield.\n"
            f"No email has been sent. This is a DRAFT for human review.\n"
            f"\n"
            f"--- SupplyShield Automated Planner (MOCK) ---\n"
        )
        email_path = OUTBOX / f"EMAIL-{po_number}.txt"
        email_path.write_text(email_text, encoding="utf-8")
        files.append(str(email_path))

        email_payload = {
            "to": "procurement@mockcompany.example",
            "subject": f"[DRAFT] Alternative Supply \u2014 {sku} \u2014 {po_number}",
            "po_number": po_number,
            "status": "DRAFT — not sent",
        }
        _record_action(job_id, "email", "executed", email_payload)

    return files
